"""Appendix table of the published leaderboard (no typed values).

Reads the latest results/leaderboard_analysis_*.json (built from paper/leaderboard.tsv, every row checked against
its source paper) and writes paper/generated/tab_leaderboard.tex: per (paper, dataset), the paper's own BER, the
lowest BER of any other method in its own main table, the claimed gain and whether it is below the one-run
seed-noise threshold. BER values are printed exactly as the papers report them.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CITE = {"scGAN": "nguyen2017scgan", "ST-CGAN": "wang2018stacked", "DSC": "hu2018direction",
        "BDRAR": "zhu2018bidirectional", "A+D Net": "le2018adnet", "DSD": "zheng2019distraction",
        "MTMT-Net": "chen2020multitask", "FDRNet": "zhu2021mitigating", "SDCM": "zhu2022sdcm",
        "SDDNet": "cong2023sddnet", "SILT": "yang2023silt", "SAM-Adapter": "chen2023samadapter",
        "AdapterShadow": "jie2023adaptershadow", "SwinShadow": "wang2024swinshadow", "TICA": "zhu2024tica"}


def esc(s):
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def main():
    p = sorted((ROOT / "results").glob("leaderboard_analysis_*.json"))[-1]
    a = json.loads(p.read_text())
    tex = [f"% generated by code/make_leaderboard_table.py from {p.name} -- do not edit",
           "\\begin{tabular}{@{}llllllc@{}}", "\\toprule",
           "Dataset & Method & Year & Own BER & Best other in own table & Claimed gain & Below 1-run seed noise \\\\",
           "\\midrule"]
    for d in ("ISTD", "SBU"):
        rs = [r for r in a["rows"] if r["dataset"] == d]
        for i, r in enumerate(rs):
            gain = f"{r['claimed_gain']:.2f}"
            tex.append(f"{d if i == 0 else ''} & {esc(r['paper'])} \\citep{{{CITE[r['paper']]}}} & {r['year']} & "
                       f"{r['own_ber']} & {esc(r['best_other_method'])} ({r['best_other_ber']}) & {gain} & "
                       f"{'yes' if r['below_seed_only'] else 'no'} \\\\")
        tex.append("\\midrule" if d == "ISTD" else "\\bottomrule")
    tex.append("\\end{tabular}")
    out = ROOT / "paper" / "generated" / "tab_leaderboard.tex"
    out.write_text("\n".join(tex) + "\n"); print(out, p.name)


if __name__ == "__main__":
    main()
