"""Appendix tables generated from the held-out retrain result files (no typed values).

Writes paper/generated/tab_hparams.tex: phase-2 (ISTD) settings of the four development-sequence models,
read from the `config` block of each dev_models/results/obj2/{arch}_phase2_heldout*.json (five seeds per
model), with the epochs run and the epoch kept for each seed. Fails if the seeds of one model differ in
anything but the seed, the output tag and run-specific bookkeeping, or if the validation scenes differ
from data/istd_struct/split.json.

Parameter-group names follow the docstrings of get_discriminative_param_groups in
dev_models/src/models/obj2_variants.py and siran_notebook.py: encoder blocks 1-2 at 0.05x, the rest of the
encoder at 0.1x, the BiFPN neck at 0.5x, decoder and heads at 1x the phase-2 base learning rate.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "dev_models" / "results" / "obj2"
OUT = ROOT / "paper" / "generated"
ARCHS = [("unetpp", "UNet++"), ("ran", "BiFPN-RAN"), ("siran", "BiFPN-SIRAN"), ("rarm", "BiFPN-RARM")]
VARIABLE = {"seed", "tag", "assumptions", "frozen_modules", "arch"}   # checked separately below
GROUP_NAME = {0.05: "encoder 1--2", 0.1: "encoder", 0.5: "BiFPN", 1.0: "decoder"}


def sci(x):
    e = int(math.floor(math.log10(x)))
    m = x / 10 ** e
    return f"$10^{{{e}}}$" if math.isclose(m, 1.0, rel_tol=1e-9) else f"${m:g}\\times10^{{{e}}}$"


def runs(arch):
    fs = sorted(f for f in RES.glob(f"{arch}_phase2_heldout*.json") if "timing" not in f.name)
    ds = [json.loads(f.read_text()) for f in fs]
    ds.sort(key=lambda d: d["config"]["seed"])
    assert [d["config"]["seed"] for d in ds] == list(range(5)), (arch, [d["config"]["seed"] for d in ds])
    ref = {k: v for k, v in ds[0]["config"].items() if k not in VARIABLE and not k.endswith("sha256")}
    for d in ds[1:]:
        c = {k: v for k, v in d["config"].items() if k not in VARIABLE and not k.endswith("sha256")}
        diff = {k for k in set(ref) | set(c) if ref.get(k) != c.get(k)}
        assert not diff, (arch, d["config"]["seed"], diff)
        assert (d["config"].get("frozen_modules") or []) == (ds[0]["config"].get("frozen_modules") or [])
    # early SIRAN runs (seeds 0-2) predate the `arch` field; the file name identifies the model
    assert all(d["config"].get("arch") in (None, arch) for d in ds), arch
    return ds


def main():
    split = json.loads((ROOT / "data" / "istd_struct" / "split.json").read_text())
    rows, notes = [], []
    for arch, name in ARCHS:
        ds = runs(arch)
        c = ds[0]["config"]
        assert c["val_scenes"] == split["val_scenes"], arch
        assert c["train_images"] == split["counts"]["train_heldout"] and c["val_images"] == split["counts"]["val_heldout"]
        base = c["base_lr_phase2"]
        mults = [round(lr / base, 4) for lr in c["param_group_lrs"]]
        groups = []
        for mult, n in zip(mults, c["param_group_sizes"]):
            if len(mults) == 1:
                label = "all parameters"            # UNet++: one group at the base rate
            elif mult == 0.1 and 0.05 in mults:
                label = "encoder 3--5"              # custom encoder: blocks 1-2 have their own group
            else:
                label = GROUP_NAME[mult]
            groups.append(f"{label} {mult:g}$\\times$ ({n})")
        frozen = c.get("frozen_modules") or []
        ran = [len(d["epochs"]) for d in ds]
        kept = [d["best"]["epoch"] for d in ds]
        drop = "--" if "not used" in str(c.get("assumptions", {}).get("dropout_p", "")) else f"{c['dropout_p']:g}"
        rows.append(f"{name} & {c['batch_size']} & {drop} & "
                    f"{', '.join(groups)}{'; stem frozen' if 'stem' in frozen else ''} & "
                    f"{', '.join(map(str, ran))} & {', '.join(map(str, kept))} \\\\")
        notes.append((name, c["epochs"], c["patience"], c["overfit_gap"], c["overfit_patience"], c["grad_clip"],
                      base, c["weight_decay"]))
    # settings shared by all four models
    shared = {n[1:] for n in notes}
    assert len(shared) == 1, shared
    epochs, patience, gap, gap_pat, clip, base, wd = shared.pop()
    tex = [
        "% generated by code/make_appendix_tables.py -- do not edit",
        "\\begin{table}[h]",
        "\\centering\\footnotesize",
        "\\caption{Phase-2 (ISTD) settings of the held-out retrains, read from their result files. "
        "Learning-rate groups: multiplier of the base learning rate, with the number of parameter tensors "
        "in parentheses. Epochs run and epoch kept are listed for seeds 0--4; the kept checkpoint is the one "
        "with the highest validation IoU. "
        f"Shared by all models: AdamW with base learning rate {sci(base)} and weight decay {sci(wd)}; at most {epochs} epochs; early stopping after {patience} epochs "
        f"without a gain in validation IoU, or after {gap_pat} consecutive epochs with a training--validation "
        f"IoU gap above {gap:g}; gradient norm clipped to {clip:g}; validation on the {split['counts']['val_heldout']} "
        f"images of ISTD training scenes {', '.join(sorted(split['val_scenes'], key=int))}; training on the "
        f"remaining {split['counts']['train_heldout']:,} images.}}",
        "\\label{tab:hparams}",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lccL{6.6cm}L{2.5cm}L{2.5cm}@{}}",
        "\\toprule",
        "Model & Batch & Dropout & Learning-rate groups & Epochs run & Epoch kept \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tab_hparams.tex").write_text("\n".join(tex) + "\n")
    print(OUT / "tab_hparams.tex")


if __name__ == "__main__":
    main()
